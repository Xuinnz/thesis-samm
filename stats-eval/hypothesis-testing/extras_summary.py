#!/usr/bin/env python3
"""
The main study and the panel's extras, side by side.

Finds every campaign under a results root (main-study, replicates-k*-mem*,
replicates-k*-d0*), applies the approved decision rule to each exactly as
main_study_stats.py does, and writes one table: variant, runs completing,
each primary metric for both conditions, the relative change, the test's p and
the decision on H0. A campaign that fails verify_campaign.py is listed as such
and not tested.

Usage: extras_summary.py RESULTS_ROOT [--baseline jemalloc] [--treatment samm]
Writes RESULTS_ROOT/extras-summary.md.
"""

import argparse
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import main_study_stats as mss  # noqa: E402
import verify_campaign  # noqa: E402


def label(folder, locked):
    rps = locked.get('max_rps')
    parts = [f"k = {locked.get('k', '?')}" + (f" holds, peak {float(rps):,.0f} req/s" if rps else ""),
             f"{locked.get('mem_limit', '?')} container"]
    parts.append("traffic: " + locked.get("traffic_batch", "?"))
    return os.path.basename(folder), ", ".join(parts)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("root")
    ap.add_argument("--baseline", default="jemalloc")
    ap.add_argument("--treatment", default="samm")
    args = ap.parse_args()

    folders = [f for pattern in ("main-study", "replicates-k*-mem*", "replicates-k*-d0*")
               for f in sorted(glob.glob(os.path.join(args.root, pattern)))
               if os.path.exists(os.path.join(f, "campaign.json"))]
    if not folders:
        sys.exit(f"no campaigns under {args.root}")
    md = ["<!-- Generated by stats-eval/hypothesis-testing/extras_summary.py. -->", "",
          f"Bonferroni-adjusted alpha {mss.ALPHA_ADJUSTED:.4f}; the test is chosen per metric by the approved rule.", "",
          "| Campaign | Setting | Runs completing, baseline / SAMM | Metric | Baseline, mean ± SD | SAMM, mean ± SD "
          "| Relative change | Test | *p* | Decision on H₀ |",
          "| :--- | :--- | :---: | :--- | ---: | ---: | ---: | :--- | ---: | :--- |"]
    for folder in folders:
        locked = json.load(open(os.path.join(folder, "campaign.json")))["locked"]
        name, setting = label(folder, locked)
        integrity = verify_campaign.verify(folder, [args.baseline, args.treatment])
        if integrity["errors"]:
            md.append(f"| {name} | {setting} | | not tested: {integrity['errors'][0]} | | | | | | |")
            continue
        base, treat = mss.load(folder, args.baseline), mss.load(folder, args.treatment)
        done = f"{sum(not r['killed'] for r in base)} of {len(base)} / {sum(not r['killed'] for r in treat)} of {len(treat)}"
        for key, metric, unit in mss.PRIMARY:
            x, y = mss.values(base, key), mss.values(treat, key)
            dx, dy = mss.describe(x), mss.describe(y)
            res = mss.primary_test(x, y)
            rel = 100.0 * (dy["mean"] - dx["mean"]) / dx["mean"] if x and y and dx["mean"] else float("nan")
            decision = "n/a" if res["p"] != res["p"] else ("Reject" if res["reject_h0"] else "Fail to reject")
            md.append(f"| {name} | {setting} | {done} | {metric}, {unit} | {mss.fmt(dx['mean'])} ± {mss.fmt(dx['sd'])} "
                      f"| {mss.fmt(dy['mean'])} ± {mss.fmt(dy['sd'])} | {'n/a' if rel != rel else f'{rel:+.1f}%'} | {res['test']} | {mss.fmt_p(res['p'])} "
                      f"| {decision} |")
            name = setting = done = ""
    text = "\n".join(md)
    print(text)
    with open(os.path.join(args.root, "extras-summary.md"), "w") as f:
        f.write(text + "\n")


if __name__ == "__main__":
    main()
